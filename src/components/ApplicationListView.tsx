import React, { useState } from 'react';
import {
  FileText,
  Plus,
  ChevronRight,
  Filter,
  Inbox,
  Clock,
  CheckCircle2,
  XCircle,
  Sparkles,
  AlertCircle
} from 'lucide-react';
import { useApp } from '../context/AppContext';
import { ApplicationStatus } from '../types';

export const ApplicationListView: React.FC = () => {
  const {
    currentUser,
    applications,
    setSelectedApplicationId,
    setActiveView,
    createNewChat
  } = useApp();

  const [statusFilter, setStatusFilter] = useState<'all' | ApplicationStatus>('all');

  const isFaculty = currentUser?.role === 'faculty';

  // For faculty: show only applications shared with them (or recipient inbox)
  // For students: show their own applications
  const userApplications = applications.filter((app) => {
    if (isFaculty) {
      // Shared with this faculty member or matching name
      return app.status !== 'draft' && (app.facultyId === currentUser?.id || app.facultyName?.includes(currentUser?.fullName || ''));
    } else {
      return app.studentId === currentUser?.id;
    }
  });

  const filteredApplications = userApplications.filter((app) => {
    if (statusFilter === 'all') return true;
    return app.status === statusFilter;
  });

  const handleRowClick = (appId: string) => {
    setSelectedApplicationId(appId);
    setActiveView('application_detail');
  };

  const handleCreateNew = () => {
    createNewChat('application_agent');
  };

  const getStatusBadge = (status: ApplicationStatus) => {
    switch (status) {
      case 'draft':
        return (
          <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-xs font-semibold bg-gray-100 text-gray-700 border border-gray-200">
            <Clock className="w-3 h-3 text-gray-500" />
            Draft
          </span>
        );
      case 'sent':
        return (
          <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-xs font-semibold bg-sky-50 text-sky-700 border border-sky-200">
            <Clock className="w-3 h-3 text-sky-600" />
            {isFaculty ? 'Pending Review' : 'Sent'}
          </span>
        );
      case 'approved':
        return (
          <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-xs font-semibold bg-emerald-50 text-emerald-700 border border-emerald-200">
            <CheckCircle2 className="w-3 h-3 text-emerald-600" />
            Approved
          </span>
        );
      case 'rejected':
        return (
          <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-xs font-semibold bg-rose-50 text-rose-700 border border-rose-200">
            <XCircle className="w-3 h-3 text-rose-600" />
            Rejected
          </span>
        );
      case 'revision_requested':
        return (
          <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-xs font-semibold bg-amber-50 text-amber-700 border border-amber-200">
            <AlertCircle className="w-3 h-3 text-amber-600" />
            Revision Requested
          </span>
        );
    }
  };

  return (
    <div className="flex-1 overflow-y-auto bg-brand-surface/40 p-4 sm:p-8">
      <div className="max-w-4xl mx-auto space-y-6">
        {/* Header */}
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-brand-border/60">
          <div>
            <h2 className="font-heading font-bold text-2xl text-brand-primary tracking-tight">
              {isFaculty ? 'Faculty Review Inbox' : 'Applications'}
            </h2>
            <p className="text-xs text-brand-muted mt-1">
              {isFaculty
                ? 'Review and decide student academic leave, bonafide requests, and internship NOCs.'
                : 'Manage formal letters generated by the AI Application Agent and track professor decisions.'}
            </p>
          </div>

          {/* Student "Create Application" button (shown only to students and when >= 1 exists) */}
          {!isFaculty && userApplications.length > 0 && (
            <button
              onClick={handleCreateNew}
              className="inline-flex items-center gap-2 px-4 py-2.5 rounded-xl bg-brand-accent hover:bg-brand-accentHover text-white text-xs font-semibold shadow-card transition-all"
            >
              <Plus className="w-4 h-4" />
              <span>Create Application</span>
            </button>
          )}
        </div>

        {/* Filter Chips */}
        <div className="flex items-center gap-2 overflow-x-auto pb-1">
          <span className="text-xs text-brand-muted font-medium flex items-center gap-1 mr-1">
            <Filter className="w-3.5 h-3.5" /> Filter:
          </span>

          <button
            onClick={() => setStatusFilter('all')}
            className={`px-3 py-1.5 rounded-xl text-xs font-medium transition-all ${
              statusFilter === 'all'
                ? 'bg-brand-primary text-white shadow-subtle'
                : 'bg-white border border-brand-border text-brand-muted hover:text-brand-primary'
            }`}
          >
            All ({userApplications.length})
          </button>

          {!isFaculty && (
            <button
              onClick={() => setStatusFilter('draft')}
              className={`px-3 py-1.5 rounded-xl text-xs font-medium transition-all ${
                statusFilter === 'draft'
                  ? 'bg-brand-primary text-white shadow-subtle'
                  : 'bg-white border border-brand-border text-brand-muted hover:text-brand-primary'
              }`}
            >
              Drafts ({userApplications.filter(a => a.status === 'draft').length})
            </button>
          )}

          <button
            onClick={() => setStatusFilter('sent')}
            className={`px-3 py-1.5 rounded-xl text-xs font-medium transition-all ${
              statusFilter === 'sent'
                ? 'bg-brand-primary text-white shadow-subtle'
                : 'bg-white border border-brand-border text-brand-muted hover:text-brand-primary'
            }`}
          >
            {isFaculty ? 'Pending' : 'Sent'} ({userApplications.filter(a => a.status === 'sent').length})
          </button>

          <button
            onClick={() => setStatusFilter('approved')}
            className={`px-3 py-1.5 rounded-xl text-xs font-medium transition-all ${
              statusFilter === 'approved'
                ? 'bg-brand-primary text-white shadow-subtle'
                : 'bg-white border border-brand-border text-brand-muted hover:text-brand-primary'
            }`}
          >
            Approved ({userApplications.filter(a => a.status === 'approved').length})
          </button>

          <button
            onClick={() => setStatusFilter('rejected')}
            className={`px-3 py-1.5 rounded-xl text-xs font-medium transition-all ${
              statusFilter === 'rejected'
                ? 'bg-brand-primary text-white shadow-subtle'
                : 'bg-white border border-brand-border text-brand-muted hover:text-brand-primary'
            }`}
          >
            Rejected ({userApplications.filter(a => a.status === 'rejected').length})
          </button>

          <button
            onClick={() => setStatusFilter('revision_requested')}
            className={`px-3 py-1.5 rounded-xl text-xs font-medium transition-all ${
              statusFilter === 'revision_requested'
                ? 'bg-brand-primary text-white shadow-subtle'
                : 'bg-white border border-brand-border text-brand-muted hover:text-brand-primary'
            }`}
          >
            Revision Requested ({userApplications.filter(a => a.status === 'revision_requested').length})
          </button>
        </div>

        {/* Application List Rows */}
        {filteredApplications.length === 0 ? (
          /* Empty State (PRD Section 7.3 & 21.1) */
          <div className="py-16 text-center rounded-3xl border border-dashed border-brand-border bg-white p-8 space-y-4">
            <div className="w-12 h-12 rounded-2xl bg-brand-surface border border-brand-border/60 mx-auto flex items-center justify-center text-brand-muted">
              <Inbox className="w-6 h-6" />
            </div>

            <div className="space-y-1">
              <h3 className="font-heading font-semibold text-base text-brand-primary">
                No applications found
              </h3>
              <p className="text-xs text-brand-muted max-w-sm mx-auto">
                {isFaculty
                  ? 'You currently have no incoming student applications in this filter queue.'
                  : 'You have not drafted any academic requests yet. Use the Application Agent to create one in seconds.'}
              </p>
            </div>

            {!isFaculty && (
              <button
                onClick={handleCreateNew}
                className="inline-flex items-center gap-2 px-5 py-2.5 rounded-xl bg-brand-accent hover:bg-brand-accentHover text-white text-xs font-semibold shadow-card transition-all"
              >
                <Plus className="w-4 h-4" />
                <span>Create Application</span>
              </button>
            )}
          </div>
        ) : (
          <div className="bg-white rounded-2xl border border-brand-border shadow-subtle divide-y divide-brand-borderSubtle overflow-hidden">
            {filteredApplications.map((app) => (
              <div
                key={app.id}
                onClick={() => handleRowClick(app.id)}
                className="p-4 sm:p-5 flex items-center justify-between gap-4 hover:bg-brand-surface/60 transition-colors cursor-pointer group text-left"
              >
                <div className="flex items-start gap-3 min-w-0 flex-1">
                  <div className="w-10 h-10 rounded-xl bg-brand-surface border border-brand-borderSubtle flex items-center justify-center text-brand-secondary shrink-0 group-hover:border-brand-accent/40 transition-colors">
                    <FileText className="w-5 h-5 text-brand-accent" />
                  </div>

                  <div className="min-w-0 flex-1">
                    <div className="flex items-center gap-2 flex-wrap mb-1">
                      <h4 className="font-heading font-semibold text-sm text-brand-primary group-hover:text-brand-accent transition-colors truncate">
                        {app.title}
                      </h4>
                      {getStatusBadge(app.status)}
                    </div>

                    <div className="flex items-center gap-3 text-xs text-brand-muted flex-wrap">
                      {isFaculty ? (
                        <span>
                          From: <strong className="text-brand-primary font-medium">{app.studentName}</strong> ({app.studentRollNumber})
                        </span>
                      ) : (
                        <span>
                          Recipient: <strong className="text-brand-primary font-medium">{app.facultyName || 'Not yet assigned'}</strong>
                        </span>
                      )}
                      <span>•</span>
                      <span>
                        Created: {new Date(app.createdAt).toLocaleDateString('en-IN', { month: 'short', day: 'numeric', year: 'numeric' })}
                      </span>
                      {app.decidedAt && (
                        <>
                          <span>•</span>
                          <span className="text-brand-secondary font-medium">
                            Decided: {new Date(app.decidedAt).toLocaleDateString('en-IN', { month: 'short', day: 'numeric' })}
                          </span>
                        </>
                      )}
                    </div>
                  </div>
                </div>

                <ChevronRight className="w-4 h-4 text-brand-muted group-hover:text-brand-primary group-hover:translate-x-0.5 transition-all shrink-0" />
              </div>
            ))}
          </div>
        )}
      </div>
    </div>
  );
};
